const seen = new Set();
const out = [];
for (const [cat, kw, name] of WANT) {
  const slugs = Object.keys(db[cat] || {});
  const matches = slugs.filter((s) => s.includes(kw)).sort((a, b) => a.length - b.length);
  if (!matches.length) continue;
  const slug = matches[0];
  const key = `${cat}/${slug}`;
  if (seen.has(key)) continue;
  seen.add(key);
  out.push({ platform: cat, slug, name, url: `https://www.retrogames.cc/${cat}/${slug}.html` });
}
fs.writeFileSync('/tmp/genre-candidates.json', JSON.stringify(out, null, 2));
console.log(`${out.length} unique candidates -> /tmp/genre-candidates.json`);
