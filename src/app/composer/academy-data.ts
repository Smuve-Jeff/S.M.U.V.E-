const buildStages = (seed: ProgramSeed): AcademyStage[] => {
  const stages = FAMILY_STAGES[seed.family];
  const levels = ['Foundation', 'Intermediate', 'Advanced'] as const;
  return stages.map((stage, stageIndex) => ({
    id: `${seed.id}-stage-${stageIndex + 1}`,
    label: stage.label,
    level: levels[stageIndex],
    summary: stage.summary,
    lessons: stage.lessons.map((lesson, lessonIndex) => ({
      id: `${seed.id}-s${stageIndex + 1}-l${lessonIndex + 1}`,
      title: lesson.title,
      focus: lesson.focus,
      drill: lesson.drill
        .replace('{technique}', seed.technique)
        .replace('{skills}', seed.skills.join(', ')),
      criteria: lesson.criteria,
      minutes: lesson.minutes,
      tempo: lesson.tempo,
      studioStep: `${seed.label} · ${lesson.title}`,
    })),
  }));
};

